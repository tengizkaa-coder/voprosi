import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1100}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://localhost:3000');await page.getByRole('heading',{name:'О чём поговорим сегодня?'}).waitFor();
await page.screenshot({path:'/tmp/between-desktop.png',fullPage:true});
await page.getByRole('button',{name:'Обсудили',exact:true}).click();
await page.waitForTimeout(150);
let state=JSON.parse(await page.evaluate(()=>localStorage.getItem('between-progress-v1')));
assert.equal(state.asked.length,1);assert.equal(state.asked[0].id,1);assert.equal(state.current,2);
await page.reload();await page.getByRole('heading',{name:'Какой запах мгновенно делает тебя счастливее?'}).waitFor();
await page.getByRole('button',{name:'Все категории'}).click();
await page.locator('.all-categories button').filter({hasText:'С самого начала'}).click();
await page.getByRole('button',{name:'Случайный',exact:true}).click();
state=JSON.parse(await page.evaluate(()=>localStorage.getItem('between-progress-v1')));assert.notEqual(state.current,1);assert.ok(state.current<=67);
await page.locator('.sidebar nav button').filter({hasText:'Наша история'}).click();await page.locator('.history-list article').waitFor();
await page.locator('.history-list article button').click();await page.getByRole('button',{name:'Да, вернуть вопрос'}).click();
await page.getByRole('heading',{name:'Здесь будут ваши разговоры'}).waitFor();
await page.setViewportSize({width:390,height:844});await page.locator('.mobile-nav button').filter({hasText:'Вопросы'}).click();await page.screenshot({path:'/tmp/between-mobile.png',fullPage:true});
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'No horizontal overflow');
assert.deepEqual(errors,[]);await browser.close();console.log('UI checks passed: mark, persist, reload, random excludes asked, undo, mobile overflow; no runtime errors.');
